    /// The invocation `install_key` makes, as `FakeRunner` records it.
    fn the_ssh_call(fake: &FakeRunner) -> String {
        fake.calls()
            .into_iter()
            .find(|call| call.starts_with("ssh "))
            .expect("an ssh call")
    }

    #[tokio::test]
    async fn the_copy_goes_through_riabuilds_pinned_host_key_and_askpass_helper() {
        let home = tempfile::TempDir::new().expect("tempdir");
        let paths = RealPaths::rooted_at(home.path());
        let fake = Arc::new(FakeRunner::new().containing("authorized_keys", 0, "", ""));

        install_key(&remote(), &paths, fake.clone(), KEY, None)
            .await
            .expect("added");

        let call = the_ssh_call(&fake);
        assert!(call.contains("-p 2222"), "{call}");
        assert!(call.contains("-F /dev/null"), "{call}");
        assert!(
            call.contains(&format!(
                "UserKnownHostsFile={}",
                paths.known_hosts_file().to_string_lossy()
            )),
            "the copy must not trust a host afresh: {call}"
        );
        assert!(call.contains("StrictHostKeyChecking=yes"), "{call}");
        // The one step that does *not* pin IdentitiesOnly: on the common
        // cloud VM the developer's existing key or agent is what proves who
        // we are while the new key is being installed.
        assert!(!call.contains("IdentitiesOnly"), "{call}");
        // And it must be able to fall back to a password, which BatchMode
        // forbids outright.
        assert!(!call.contains("BatchMode"), "{call}");

        let env = fake.env_of("ssh");
        for (key, value) in askpass::ssh_env(&remote(), &paths) {
            assert!(
                env.contains(&(key.clone(), value.clone())),
                "the copy lost its askpass helper, so the password is asked for again: {env:?}"
            );
        }
    }

