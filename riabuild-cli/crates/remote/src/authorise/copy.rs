    #[cfg(unix)]
    #[tokio::test]
    async fn an_account_that_has_never_used_ssh_gets_a_private_directory_and_file() {
        // sshd refuses a key directory or file that others can read, so
        // creating either at the account's umask would install a key that
        // cannot work and say nothing about why.
        use std::os::unix::fs::PermissionsExt;

        let home = tempfile::TempDir::new().expect("tempdir");

        let output = run_on(home.path(), KEY).await;
        assert_eq!(output.code, Some(0), "{}", output.stderr);

        let mode = |path: std::path::PathBuf| async move {
            tokio::fs::metadata(path)
                .await
                .expect("stat")
                .permissions()
                .mode()
                & 0o777
        };
        assert_eq!(mode(home.path().join(".ssh")).await, 0o700);
        assert_eq!(mode(home.path().join(".ssh/authorized_keys")).await, 0o600);
    }

    #[cfg(unix)]
    #[tokio::test]
    async fn an_existing_ssh_directory_keeps_the_mode_the_developer_gave_it() {
        // Same rule as `identity::ensure_key`'s directory handling read from
        // the other side: what riabuild creates it locks down, what it finds
        // is the account owner's business.
        use std::os::unix::fs::PermissionsExt;

        let home = tempfile::TempDir::new().expect("tempdir");
        seed(home.path(), "").await;
        tokio::fs::set_permissions(
            home.path().join(".ssh"),
            std::fs::Permissions::from_mode(0o755),
        )
        .await
        .expect("chmod");

        run_on(home.path(), KEY).await;

        let mode = tokio::fs::metadata(home.path().join(".ssh"))
            .await
            .expect("stat")
            .permissions()
            .mode()
            & 0o777;
        assert_eq!(
            mode, 0o755,
            "riabuild must not chmod what it did not create"
        );
    }

    #[cfg(unix)]
    #[tokio::test]
    async fn a_comment_full_of_shell_metacharacters_is_inert() {
        // The comment reaches the server inside a `/bin/sh -c` string. A key
        // whose comment contains a quote or a substitution must land in the
        // file verbatim rather than running.
        let home = tempfile::TempDir::new().expect("tempdir");
        let nasty = format!(
            "ssh-ed25519 {BODY} riabuild 'x' $(touch {}/pwned) `id`",
            home.path().display()
        );

        let output = run_on(home.path(), &nasty).await;

        assert_eq!(output.code, Some(0), "{}", output.stderr);
        assert!(
            !home.path().join("pwned").exists(),
            "the comment was executed rather than written"
        );
        assert_eq!(authorized_keys(home.path()).await.trim_end(), nasty);
    }

