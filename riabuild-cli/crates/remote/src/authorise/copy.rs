    #[tokio::test]
    async fn a_copy_that_actually_failed_says_what_the_server_said() {
        // Distinct from the two above: a read-only home, a full disk, a
        // connection that dropped. It carries no remedy of its own — whether
        // a failure here stops the run or becomes a warning beside a password
        // fallback is `authorise`'s call, and it is `authorise` that owns the
        // "add this line to authorized_keys" wording. Two copies of that
        // instruction in one message is what happens when both layers write
        // one.
        let home = tempfile::TempDir::new().expect("tempdir");
        let paths = RealPaths::rooted_at(home.path());
        let fake = Arc::new(FakeRunner::new().containing(
            "authorized_keys",
            1,
            "",
            "sh: cannot create /home/ada/.ssh/authorized_keys: Read-only file system",
        ));

        let error = install_key(&remote(), &paths, fake, KEY, None)
            .await
            .expect_err("a failed copy must not read as success");

        let said = error.to_string();
        assert!(
            said.contains("Read-only"),
            "the server's own words are the whole diagnostic here: {said}"
        );
        assert!(
            !said.to_lowercase().contains("add this line"),
            "the remedy belongs to the caller: {said}"
        );
    }

