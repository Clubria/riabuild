    #[test]
    fn the_ngrok_shim_keeps_the_token_out_of_the_file_and_out_of_every_argument_list() {
        // `ps` is world-readable, and on a shared server it shows every other
        // developer's command lines. The token reaches ngrok through the
        // environment or not at all — and it is fetched by the process that
        // *becomes* ngrok, so it is never a shell variable either.
        let script = ngrok_shim_script(
            server_binary(),
            Path::new("/home/dev/.riabuild/ngrok/3.39.11/ngrok"),
        );
        assert!(!script.contains("--authtoken"), "{script}");
        assert!(!script.contains("config add-authtoken"), "{script}");
        assert!(!script.contains("NGROK_AUTHTOKEN"), "{script}");
        // And no command substitution. The shim used to read the token off
        // `internal ngrok-token`'s stdout, which made "print nothing else on
        // stdout" a rule the whole of that subcommand had to keep, and put a
        // credential in a shell variable in a process that then went on to
        // `exec`.
        assert!(!script.contains("$("), "{script}");
    }

    /// The property the whole of `~/.riabuild/bin` is held to.
    ///
    /// Every generated file here is a shebang, some comments, and exactly one
    /// `exec`. A branch, a substitution, a pipeline or a `set --` appearing in
    /// one of them means a decision has leaked back out of Rust and into a
    /// language with no type checker and no test that runs without a
    /// subprocess — which is how the `PATH` strip, the `case "$PWD"` and the
    /// approval-policy scans came to be shell in the first place.
    ///
    /// Asserted over every generator at once, so one added later is covered on
    /// the day it is written rather than the day someone remembers to extend
    /// this.
    #[test]
    fn every_generated_script_is_a_single_exec() {
        let riabuild = server_binary();
        let ngrok = Path::new("/home/dev/.riabuild/ngrok/3.39.11/ngrok");
        let node = Path::new("/home/dev/.riabuild/node/22.23.1/bin/node");
        let checkout = std::path::PathBuf::from("/home/dev/Clubria/ai-builders-hub");

        let mut scripts = vec![
            exec_shim(ngrok),
            node_shim(
                node,
                Path::new("/home/dev/.riabuild/pnpm/11.11.0/bin/pnpm.cjs"),
            ),
            ngrok_shim_script(riabuild, ngrok),
            infisical_shim_script(
                riabuild,
                Path::new("/home/dev/.riabuild/infisical/0.43.120/infisical"),
            ),
            browser_shim_script(riabuild),
            agents_shim_script(riabuild),
            claude::launcher_script(
                riabuild,
                Path::new("/home/dev/.riabuild/claude/abc"),
                "/home/dev/.riabuild/node/22.23.1/bin/claude",
                Path::new("/home/dev/.riabuild/org-settings.json"),
                Path::new("/home/dev/.riabuild/bin"),
                std::slice::from_ref(&checkout),
                Some(&checkout),
            ),
            codex::launcher_script(
                riabuild,
                Path::new("/home/dev/.riabuild/codex/1"),
                "/home/dev/.riabuild/node/22.23.1/bin/codex",
                Path::new("/home/dev/.riabuild/bin"),
            ),
            grok::launcher_script(
                riabuild,
                Path::new("/home/dev/.riabuild/grok/1"),
                "/home/dev/.riabuild/grok/1.0.5/grok",
                Path::new("/home/dev/.riabuild/bin"),
            ),
        ];
        scripts.extend(
            CLIPBOARD_TOOLS
                .iter()
                .map(|tool| clipboard_shim_script(riabuild, tool)),
        );

        for script in scripts {
            assert!(script.starts_with("#!/bin/sh\n"), "{script}");
            let code: Vec<&str> = script
                .lines()
                .map(str::trim)
                .filter(|line| !line.is_empty() && !line.starts_with('#'))
                .collect();
            assert_eq!(code.len(), 1, "{script}");
            assert!(code[0].starts_with("exec "), "{script}");
            for forbidden in [
                "if ", "case ", "for ", "while ", "set --", "$(", "|", "&&", ";",
            ] {
                assert!(
                    !code[0].contains(forbidden),
                    "`{forbidden}` in a generated script:\n{script}"
                );
            }
            // The developer's own arguments reach the far side, every time.
            assert!(code[0].ends_with(r#""$@""#), "{script}");
        }
    }

    /// The infisical binary is riabuild's to resolve, not the shim's to name.
    ///
    /// `internal infisical` asks `Ctx::infisical` for it, which is the same
    /// question every other riabuild call asks. A path baked in here would be a
    /// second answer, and the two disagree for as long as it takes a version
    /// bump to rewrite this file.
    #[test]
    fn the_infisical_shim_hands_the_whole_invocation_to_riabuild() {
        let script = infisical_shim_script(
            server_binary(),
            Path::new("/home/dev/.riabuild/infisical/0.43.120/infisical"),
        );
        assert!(
            script.contains(&format!(
                r#"exec {} internal infisical "$@""#,
                shell_quote(&server_binary().to_string_lossy())
            )),
            "{script}"
        );
        assert!(!script.contains("0.43.120"), "{script}");
    }

    /// Nothing in this script may hold the credential, which is the whole
    /// reason it is four lines rather than ngrok's twelve.
    ///
    /// Five values would have to come back from riabuild as text, and both
    /// shapes for reading text into a POSIX shell are worse than the problem:
    /// an `eval` of what the server said, or a here-document, which dash and
    /// most other shells write to a file in `/tmp` first.
    #[test]
    fn the_infisical_shim_never_handles_the_credential_itself() {
        let script = infisical_shim_script(
            server_binary(),
            Path::new("/home/dev/.riabuild/infisical/0.43.120/infisical"),
        );
        assert!(!script.contains("INFISICAL_TOKEN"), "{script}");
        assert!(!script.contains("eval"), "{script}");
        assert!(!script.contains("<<"), "{script}");
        assert!(!script.contains("$("), "{script}");
    }

    /// A shadowed binary with no parser behind it would pass everything through
    /// — a tool that looks installed and does nothing riabuild intended.
    #[test]
    fn every_shadowed_tool_has_a_parser() {
        for tool in CLIPBOARD_TOOLS {
            assert!(
                clipboard::Tool::from_name(tool).is_some(),
                "{tool} is shimmed but the shim cannot parse it"
            );
        }
    }
