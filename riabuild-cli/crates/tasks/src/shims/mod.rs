/// `~/.riabuild/bin/<name>`, handing off to a binary in its own versioned tree.
///
/// Used for pnpm and `gh` alike. pnpm is the one that *requires* it: pnpm 11
/// loads `dist/` from beside its executable, so copying the executable onto
/// `PATH` by itself gets `Cannot find module .../dist/pnpm.mjs`. A symlink also
/// works today, because Node resolves `process.execPath` through symlinks, but
/// that is an implementation detail of the runtime pnpm happens to be built on.
///
/// `gh` is a single static binary that could be copied, and uses a shim anyway
/// so that `bin/` is uniformly a directory of small scripts and a version bump
/// rewrites one line instead of moving 30 MB.
pub fn exec_shim(binary: &Path) -> String {
    format!(
        r#"#!/bin/sh
# Generated by riabuild. Edits here are overwritten.
exec {binary} "$@"
"#,
        binary = shell_quote(&binary.to_string_lossy()),
    )
}

/// `~/.riabuild/bin/<name>`, handing off to a **script** through the Node
/// riabuild owns.
///
/// pnpm is the one that needs this, and needs it on every platform: there is no
/// pnpm executable that runs on a bare Linux. `@pnpm/linux-x64` is linked
/// against `libatomic.so.1`, which arrives with a toolchain and is therefore
/// absent from exactly the machines a provisioner is pointed at, and
/// `@pnpm/linuxstatic-x64` is musl and asks for a loader that is not there
/// either — so riabuild installs pnpm's JavaScript and hands it to the Node it
/// downloaded and verified itself. `download::PNPM_PACKAGE` carries the
/// evidence.
///
/// Both paths are absolute, for the reason in the module header and for the one
/// in `../../../CLAUDE.md`'s Codex section: during provisioning nothing riabuild
/// owns is on `PATH`, so a `#!/usr/bin/env node` shebang finds whatever Node the
/// machine has — on a server reached by a non-interactive SSH exec, whose `PATH`
/// is `/usr/local/bin:/usr/bin:/bin`, that is nothing at all, and the 127 it
/// exits with reads to `check()` as "pnpm is not installed".
pub fn node_shim(node: &Path, script: &Path) -> String {
    format!(
        r#"#!/bin/sh
# Generated by riabuild. Edits here are overwritten.
exec {node} {script} "$@"
"#,
        node = shell_quote(&node.to_string_lossy()),
        script = shell_quote(&script.to_string_lossy()),
    )
}

/// Writes `~/.riabuild/bin/<name>` for one owned tool.
///
/// This is what puts the owned copy in front of any system one for the
/// developer's own commands: `~/.riabuild/bin` is first on `PATH` inside the
/// environment shell. riabuild's own calls do not rely on it — they run the
/// versioned path directly, because during provisioning that `PATH` does not
/// exist yet.
pub async fn write_tool(ctx: &Ctx, name: &str, binary: &Path) -> Result<()> {
    write_script(&ctx.paths.bin_dir(), name, &exec_shim(binary)).await
}

/// Puts one generated script in `bin/`, executable and landed by rename.
///
/// **Every** shim and launcher this crate writes goes through here — the tool
/// shims, the clipboard three, `xdg-open`, `ngrok`, and the `claude`, `codex`
/// and `grok` launchers. There were seven copies of these same three calls, two
/// of them (`codex::write_launcher` and `grok::write_launcher`) byte-identical
/// to a third in this module, and the drift they invite is not cosmetic: a copy
/// that forgets `make_executable` writes a perfectly good script the developer
/// gets `permission denied` from, and a copy that reaches for
/// `tokio::fs::write` leaves whichever colleague is mid-`exec` a truncated
/// shell script. Both are one line missing from one of seven places, and
/// neither fails to compile.
///
/// `create_dir_all` here rather than at each caller for the same reason: a
/// launcher written into a `bin/` nobody made is `NotFound`, and it is a
/// no-op every time after the first.
pub(crate) async fn write_script(bin: &Path, name: &str, script: &str) -> Result<()> {
    tokio::fs::create_dir_all(bin).await?;
    let path = bin.join(name);
    riabuild_paths::config::write_atomic(&path, script.as_bytes()).await?;
    make_executable(&path).await?;
    Ok(())
}

/// The tools riabuild shadows in `~/.riabuild/bin`.
///
/// One per direction per session type: xclip does both on X11, and Wayland
/// splits them across wl-paste and wl-copy. Every name here must also be a
/// `Tool` the shim can parse — one without a parser would shadow a working
/// binary with one that passes everything through.
pub const CLIPBOARD_TOOLS: &[&str] = &["xclip", "wl-paste", "wl-copy"];

/// `~/.riabuild/bin/xclip`, `wl-paste` and `wl-copy`.
///
/// All three route into riabuild, which decides whether the invocation is a
/// clipboard transfer to send down the channel or something to hand to the real
/// binary. They are written on the *server*, where `~/.riabuild/bin` leads
/// `PATH` and Claude Code's probe finds them first.
///
/// Written by `provision::write_launchers`, under the same condition
/// `shell::browser_for` uses to export `BROWSER` — see the note there for why
/// the two must not drift apart.
///
/// `riabuild` is the absolute path of the binary writing them; see the module
/// header for why it can never be the bare name.
pub async fn write_clipboard_shims(ctx: &Ctx, riabuild: &Path) -> Result<()> {
    let bin = ctx.paths.bin_dir();
    // One per direction per session type: xclip does both on X11, and Wayland
    // splits them across wl-paste and wl-copy.
    for tool in CLIPBOARD_TOOLS {
        write_script(&bin, tool, &clipboard_shim_script(riabuild, tool)).await?;
    }
    Ok(())
}

/// `~/.riabuild/bin/<tool>` for one clipboard tool.
pub fn clipboard_shim_script(riabuild: &Path, tool: &str) -> String {
    format!(
        r#"#!/bin/sh
# Generated by riabuild. Edits here are overwritten.
#
# Carries the clipboard between this server and the laptop over the riabuild
# channel. Anything that is not a clipboard transfer is handed to the real
# {tool} on PATH.
#
# riabuild is named in full because it is not on PATH: it lives in its own
# versioned directory, and a bare name would find another machine's copy or
# none at all.
exec {riabuild} channel shim {tool} "$@"
"#,
        riabuild = shell_quote(&riabuild.to_string_lossy()),
    )
}

/// `~/.riabuild/bin/ngrok` — ngrok, with the team's authtoken in its
/// environment and nowhere else.
///
/// The token is the org's, it is long-lived, and riabuild does not write this
/// class of secret down: not into ngrok's own `ngrok.yml`, not into a generated
/// rcfile, not into this script. It is fetched on **every** invocation, so a
/// token a lead rotates this morning is in effect this morning, and the audit
/// row the fetch writes says somebody used the team's tunnel credential rather
/// than that somebody opened a terminal.
///
/// The token reaches ngrok in its environment and never in an argument — `ps`
/// is world-readable, and on a shared server it shows one developer's command
/// lines to all the others — and it is not in this file either, which is on
/// disk.
///
/// **This shim used to hold the one piece of shell in `bin/` that handled a
/// secret**, and it was the sharpest argument for moving all of them into Rust.
/// It read
///
/// ```sh
/// NGROK_AUTHTOKEN=$("…/riabuild" internal ngrok-token)
/// if [ -n "$NGROK_AUTHTOKEN" ]; then export NGROK_AUTHTOKEN; else unset NGROK_AUTHTOKEN; fi
/// ```
///
/// — a command substitution whose *stdout was a credential*, which made "print
/// nothing else on stdout" a rule the whole of `internal ngrok-token` had to
/// keep, and which put a token in a shell variable in a process that then went
/// on to `exec`. `riabuild internal ngrok` fetches it in the process that is
/// about to become ngrok and passes it in that process's own environment, so it
/// is never a variable in a shell, never a line on a pipe, and never anything
/// `set -x` could print.
///
/// A fetch that fails prints riabuild's own explanation on stderr and starts
/// ngrok with the variable **absent** rather than empty: an empty
/// `NGROK_AUTHTOKEN` reads to ngrok as *not authenticated* and would override a
/// token a developer had configured for themselves. ngrok still runs, because
/// `ngrok --version` and `ngrok help` should work on a plane.
///
/// `riabuild` is named in full for the reason in the module header, and so is
/// ngrok: this shim *is* what `PATH` finds, so a bare `ngrok` here would find
/// this script.
pub fn ngrok_shim_script(riabuild: &Path, ngrok: &Path) -> String {
    format!(
        r#"#!/bin/sh
# Generated by riabuild. Edits here are overwritten.
#
# Runs ngrok with the team's authtoken, fetched from riabuild-web on every
# invocation and stored nowhere on this machine. The token reaches ngrok in its
# environment and never in an argument, because `ps` shows argument lists to
# every account on the machine — and never through this file, which does no
# more than name the two binaries involved.
#
# A fetch that fails says so on stderr and leaves ngrok unauthenticated rather
# than refusing to start.
exec {riabuild} internal ngrok --binary {ngrok} -- "$@"
"#,
        riabuild = shell_quote(&riabuild.to_string_lossy()),
        ngrok = shell_quote(&ngrok.to_string_lossy()),
    )
}

/// Writes `~/.riabuild/bin/ngrok`.
///
/// Deliberately not `write_tool`: every other owned tool is handed straight to
/// `exec`, and this one has to carry a credential to the process it starts.
pub async fn write_ngrok_shim(ctx: &Ctx, riabuild: &Path, ngrok: &Path) -> Result<()> {
    let bin = ctx.paths.bin_dir();
    write_script(&bin, "ngrok", &ngrok_shim_script(riabuild, ngrok)).await
}

/// `~/.riabuild/bin/infisical` — infisical, signed in to the team's project for
/// the length of one command.
///
/// The second entry in `bin/` that is not an `exec` line, and it exists for the
/// reason `env_local` already gives: riabuild fills `.env.dev` with a
/// short-lived credential brokered from riabuild-web and written down nowhere,
/// and the developer who then typed `infisical export` themselves met a CLI
/// that had never been logged in. `infisical login` is not the answer to that —
/// it stores a credential on the machine, which is the one thing the brokering
/// design exists to avoid — so a developer's own invocation gets exactly what
/// riabuild's does: a credential minted for this command, handed over in the
/// environment, and left to expire.
///
/// **Unlike ngrok's, this shim carries nothing itself.** ngrok needs one value
/// and takes it through a command substitution. infisical needs five — the
/// token, the API URL, the project, the environment and the secret path — and
/// getting five back into a POSIX shell means either an `eval` of what the
/// server said or a here-document, which most shells implement as a temporary
/// *file*. A brokered credential in `/tmp`, however briefly, is the thing this
/// whole path exists to prevent. So riabuild fetches them and starts infisical
/// itself, and the credential exists in two process environments and nowhere
/// else.
///
/// riabuild is named in full because it is not on `PATH`, and infisical is not
/// named at all: `internal infisical` resolves the versioned copy through
/// `Ctx::infisical` like every other riabuild call, so "which infisical" has one
/// answer rather than two that can disagree after an upgrade.
pub fn infisical_shim_script(riabuild: &Path, _infisical: &Path) -> String {
    format!(
        r#"#!/bin/sh
# Generated by riabuild. Edits here are overwritten.
#
# Runs the infisical riabuild installed, against the team's project, with a
# short-lived credential brokered from riabuild-web for this one command and
# stored nowhere on this machine. riabuild fetches the credential and passes it
# in the environment of the process it starts, never in an argument, because
# `ps` shows argument lists to every account on the machine.
#
# A fetch that fails says so on stderr and runs infisical anyway, so `infisical
# --version` and `infisical scan` still work on a machine with no network.
exec {riabuild} internal infisical "$@"
"#,
        riabuild = shell_quote(&riabuild.to_string_lossy()),
    )
}

/// The tool riabuild shadows to send links to the laptop.
///
/// Named separately from `CLIPBOARD_TOOLS` because it is a different shim with
/// a different contract: the clipboard shims hand unrecognised invocations to
/// the real binary, and this one never does.
pub const BROWSER_TOOL: &str = "xdg-open";

/// What `riabuild agents` is called by the developer who uses it.
pub const AGENTS_TOOL: &str = "agents";

/// `~/.riabuild/bin/agents`.
///
/// The whole of how the feature gets its own executable name. The alternative —
/// a second binary in the workspace — would mean a `[[bin]]` in `crates/cli`,
/// an install line in the Homebrew formula, the deb and the rpm, and a second
/// artefact for `release.yml` to build, sign and strip. This is one generated
/// file in a directory riabuild already owns and already puts at the front of
/// `PATH`, and it can never disagree with the binary it came from because it
/// names it by absolute path.
pub async fn write_agents_shim(ctx: &Ctx, riabuild: &Path) -> Result<()> {
    let bin = ctx.paths.bin_dir();
    write_script(&bin, AGENTS_TOOL, &agents_shim_script(riabuild)).await
}

