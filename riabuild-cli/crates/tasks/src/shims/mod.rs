//! `~/.riabuild/bin` — the small scripts that make the environment work.
//!
//! The important ones are the Claude Code launchers: `claude` runs the primary
//! account, and `claude-1` … `claude-N` each run their own. Every one launches
//! Claude Code with that account's config directory and the org settings
//! layered over it.
//!
//! What each of them *does* lives in `claude`, beside the `codex` and `grok`
//! launchers, and is Rust: `launch` is the command they all `exec`, and the
//! reason none of them is a shell script any more. What this module owns is the
//! machinery underneath all of them — putting one generated script in `bin/`,
//! executable and landed by rename — and the shims for the tools riabuild
//! shadows there: the clipboard three, `xdg-open`, and the two that carry a
//! credential to the tool they start, `ngrok` and `infisical`.
//!
//! **Every generated script in here is one `exec` line.** That is a deliberate
//! ceiling rather than a coincidence of what they happen to need: a shell
//! script has no type checker, no test that runs without a subprocess, and a
//! parser that turns a mistake into a different working program instead of into
//! an error. A branch, a substitution or a pipeline appearing in one of these
//! files means logic has leaked back out of Rust, and
//! `every_generated_script_is_a_single_exec` fails when it does.
//!
//! Every shim here names the riabuild binary by **absolute path**, and none of
//! them may go back to a bare `riabuild`. riabuild does not put its own binary
//! on `PATH`: it lives at `<tools>/riabuild/<version>/riabuild`, while
//! `shell::riabuild_path_dirs` leads `PATH` with `bin/` and Node's `bin/` and
//! nothing else. A bare name therefore resolves to whatever *else* is called
//! riabuild on that machine — on a server with an apt or Homebrew copy, some
//! other version; on a server without one, nothing at all, and `$BROWSER`
//! becomes `xdg-open: exec: riabuild: not found`.

